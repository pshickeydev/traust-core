from __future__ import annotations

from typing import Protocol
from uuid import UUID

from traust_core.v1.models.common import Page, PageRequest
from traust_core.v1.models.portfolio import (
    CodeLine,
    Component,
    ComponentFilter,
    Product,
    ProductSlug,
    RefName,
    Release,
    Repository,
    RepositoryFilter,
    Revision,
)
from traust_core.v1.models.values import GitSha, HttpsRepoUrl
from traust_core.v1.repositories.unit_of_work import UnitOfWork


class ProductRepository(Protocol):
    def get(self, product_id: UUID) -> Product: ...
    def find_by_slug(self, slug: ProductSlug) -> Product | None: ...
    def add(self, product: Product) -> Product: ...
    def update(self, product: Product) -> Product: ...
    def list(self, page: PageRequest) -> Page[Product]: ...


class RepositoryRepository(Protocol):
    def get(self, repository_id: UUID) -> Repository: ...
    def find_by_url(self, url: HttpsRepoUrl) -> Repository | None: ...
    def add(self, repository: Repository) -> Repository: ...
    def update(self, repository: Repository) -> Repository: ...
    def list(self, filter: RepositoryFilter, page: PageRequest) -> Page[Repository]: ...


class CodeLineRepository(Protocol):
    def get(self, code_line_id: UUID) -> CodeLine: ...
    def find_by_ref(self, repository_id: UUID, ref: RefName) -> CodeLine | None: ...
    def add(self, code_line: CodeLine) -> CodeLine: ...
    def list_for(self, repository_id: UUID) -> list[CodeLine]: ...


class RevisionRepository(Protocol):
    def get(self, revision_id: UUID) -> Revision: ...
    def find_by_sha(self, repository_id: UUID, sha: GitSha) -> Revision | None: ...
    def add(self, revision: Revision) -> Revision: ...


class ComponentRepository(Protocol):
    def get(self, component_id: UUID) -> Component: ...
    def find(self, product_id: UUID, code_line_id: UUID) -> Component | None: ...
    def add(self, component: Component) -> Component: ...
    def update(self, component: Component) -> Component: ...
    def list(self, filter: ComponentFilter, page: PageRequest) -> Page[Component]: ...


class ReleaseRepository(Protocol):
    def add(self, release: Release) -> Release: ...
    def list_for(self, component_id: UUID) -> list[Release]: ...


class PortfolioUnitOfWork(UnitOfWork, Protocol):
    products: ProductRepository
    repositories: RepositoryRepository
    code_lines: CodeLineRepository
    revisions: RevisionRepository
    components: ComponentRepository
    releases: ReleaseRepository
